const assert = require("node:assert/strict");
const createSession = require("./test-session.js");
let time = 0;
const session = createSession(() => time);
session.record("balance-viewed");
assert.equal(session.status().result, null, "não coleta sem sessão");
assert.throws(() => session.start(false), /consentimento/);
session.start(true);
assert.throws(() => session.start(true), /sessão atual/);
time = 30000;
session.record("balance-viewed");
time = 60000;
session.record("human-forwarded");
session.record("feedback-yes");
session.record("mensagem pessoal não permitida");
let result = session.finish(false);
assert.equal(result.meetsExperiment2Criterion, true);
assert.equal(result.bothTasksSeconds, 60);
assert.equal(result.events.length, 3);
assert.equal(result.lastSelfReportedFeedback, "feedback-yes");
session.record("feedback-no");
assert.equal(result.events.length, 3, "não coleta após encerrar");
session.start(true);
session.record("balance-viewed");
time = 180001;
session.record("human-forwarded");
assert.equal(session.finish(false).meetsExperiment2Criterion, false, "120,001 segundos excede o limite");
session.start(true);
session.record("balance-viewed");
session.record("human-forwarded");
assert.equal(session.finish(true).meetsExperiment2Criterion, false, "orientação impede concluir autonomia");
session.start(true);
session.record("feedback-no");
result = session.finish(false);
assert.equal(result.bothTasksCompleted, false);
assert.equal(result.bothTasksSeconds, null);
assert.equal(result.lastSelfReportedFeedback, "feedback-no");
session.discard();
assert.deepEqual(session.status(), { active: false, result: null });
session.start(true);
session.record("balance-viewed");
session.record("human-forwarded");
assert.equal(session.finish().meetsExperiment2Criterion, null, "não presume ausência de orientação");
console.log("Sessões: consentimento, tempo, limite, orientação, feedback e descarte verificados.");
